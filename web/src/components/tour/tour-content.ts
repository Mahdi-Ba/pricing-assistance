/** Which tour belongs to a workspace path. */
export function tourForPath(pathname: string): TourId | null {
  if (pathname === "/queue") return "queue";
  if (pathname.startsWith("/queue/")) return "detail";
  if (pathname === "/matches") return "matches";
  if (pathname === "/reports") return "reports";
  if (pathname === "/catalog/imports") return "imports";
  if (pathname === "/rules") return "rules";
  if (pathname === "/sources") return "sources";
  if (pathname === "/settings") return "settings";
  return null;
}
